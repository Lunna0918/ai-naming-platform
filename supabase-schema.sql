-- Supabase 建表 SQL：在 Supabase SQL 编辑器中执行
-- 表名：name_history，保存每次起名的需求、结果与所用模型

create table name_history (
  id bigint generated by default as identity primary key,
  user_requirement text not null,
  name_result text not null,
  model_name text not null,
  created_at timestamp with time zone default now()
);

-- 调试阶段可临时关闭 RLS；正式上线建议开启 RLS 并按访问策略配置授权
alter table name_history enable row level security;

